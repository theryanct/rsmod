"""Builds generic-locs' loc_transports.tsv from the RuneLite Shortest Path plugin's transports.tsv.

Source: https://github.com/Skretzo/shortest-path (src/main/resources/transports/transports.tsv),
BSD 2-Clause License, Copyright (c) Skretzo. Only object (loc) transports are kept: rows whose
"menuOption menuTarget objectID" names a loc, with no quest / varbit / varp / item requirements
(those gates are left to real scripts). Skill requirements ("50 Agility") are kept.

Usage: python -I tools/travel/transports_to_tsv.py <transports.tsv> [out.tsv]
"""

import re
import sys
from pathlib import Path

OUT = Path(
    "content/generic/generic-locs/src/main/resources/org/rsmod/content/generic/locs/transports/loc_transports.tsv"
)
SKILLS = {
    "attack", "defence", "strength", "hitpoints", "ranged", "prayer", "magic", "cooking",
    "woodcutting", "fletching", "fishing", "firemaking", "crafting", "smithing", "mining",
    "herblore", "agility", "thieving", "slayer", "farming", "runecrafting", "hunter",
    "construction", "sailing",
}


def coords(text):
    parts = text.split()
    if len(parts) != 3 or not all(p.lstrip("-").isdigit() for p in parts):
        return None
    return parts


def main():
    src = Path(sys.argv[1])
    out = Path(sys.argv[2]) if len(sys.argv) > 2 else OUT
    rows = []
    skipped = 0
    for line in src.read_text(encoding="utf-8").splitlines():
        if not line.strip() or line.startswith("#"):
            continue
        p = line.split("\t") + [""] * 11
        origin, dest = coords(p[0]), coords(p[1])
        m = re.match(r"^(\S+) (.*) (\d+)$", p[2].strip())
        if not origin or not dest or not m:
            continue
        option, target, loc_id = m.group(1), m.group(2), m.group(3)
        if any(p[i].strip() for i in (4, 5, 6, 7)):  # items, quests, varbits, varps
            skipped += 1
            continue
        skills = []
        ok = True
        for req in filter(None, (s.strip() for s in p[3].split(";"))):
            sm = re.match(r"^(\d+) (\w+)$", req)
            if not sm or sm.group(2).lower() not in SKILLS:
                ok = False
                break
            skills.append(f"{sm.group(1)} {sm.group(2).lower()}")
        if not ok:
            skipped += 1
            continue
        duration = p[8].strip() or "1"
        rows.append((loc_id, option, *origin, *dest, ";".join(skills), duration, target))
    out.parent.mkdir(parents=True, exist_ok=True)
    with out.open("w", encoding="utf-8", newline="\n") as f:
        f.write("# Generated by tools/travel/transports_to_tsv.py from the RuneLite Shortest Path plugin's\n")
        f.write("# transports.tsv (https://github.com/Skretzo/shortest-path, BSD 2-Clause, Copyright (c) Skretzo).\n")
        f.write("# loc_id\toption\tox\toz\tolevel\tdx\tdz\tdlevel\tskills\tduration\ttarget\n")
        for r in rows:
            f.write("\t".join(r) + "\n")
    print(f"{len(rows)} loc transports written to {out} ({skipped} gated rows skipped)")


if __name__ == "__main__":
    main()
