"""Report repo type references whose names disappear between two symbol sets.

Usage: python -I refcheck.py <old_generated_syms_dir> <new_generated_syms_dir> [repo_root]

Compares cache-derived names (generated by gensyms.py for both caches) and lists every
`find("name")` in the repo's Kotlin sources that refers to a name present in the old cache but gone
in the new one. Flags skill modules the skilling session owns (fishing/prayer/woodcutting/cooking).
"""
import collections
import os
import re
import sys

TYPES = ['obj', 'npc', 'loc', 'varbit', 'varp', 'seq', 'spotanim', 'inv', 'dbrow', 'dbtable',
         'dbcol', 'interface', 'component', 'varc']
WATCH = ('fishing', 'prayer', 'woodcutting', 'cooking')
FIND = re.compile(r'find(?:<[^>]*>)?\(\s*"([^"]+)"')


def names(path):
    out = set()
    if not os.path.exists(path):
        return out
    for line in open(path, encoding='utf-8', errors='replace'):
        parts = line.rstrip('\r\n').split('\t')
        if len(parts) >= 2:
            out.add(parts[1])
    return out


def main(old_dir, new_dir, repo='.'):
    lost = {t: names(f'{old_dir}/{t}.sym') - names(f'{new_dir}/{t}.sym') for t in TYPES}
    hits = collections.defaultdict(list)
    total = 0
    for root, dirs, files in os.walk(repo):
        dirs[:] = [d for d in dirs if d not in ('build', '.git', '.gradle', '.data')]
        for f in files:
            if not f.endswith('.kt'):
                continue
            path = os.path.join(root, f)
            for n, line in enumerate(open(path, encoding='utf-8', errors='replace'), 1):
                for ref in FIND.findall(line):
                    total += 1
                    for t in TYPES:
                        if ref in lost[t]:
                            hits[t].append((path, n, ref))
    print(f'refs scanned: {total}')
    for t in TYPES:
        if hits[t]:
            print(f'\n## {t}: {len(hits[t])} broken (names removed in new cache: {len(lost[t])})')
            for path, n, ref in hits[t]:
                flag = ' [skilling]' if any(w in path.replace('\\', '/') for w in WATCH) else ''
                print(f'  {path}:{n}  {ref}{flag}')
    print('\nTOTAL broken:', sum(len(v) for v in hits.values()))


if __name__ == '__main__':
    main(*sys.argv[1:])
