// Data: content/skills/cooking/.../cooking.tsv, generated by tools/skills/cooking_to_tsv.py.
// Not yet: make-x (cooks the whole inventory), wine fermentation, karambwan, cakes/stews that
// need 3+ ingredients, Hosidius kitchen, gnome cooking, brewing.
class Cooking
@Inject
constructor(
    private val locTypes: LocTypeList,
    private val objTypes: ObjTypeList,
    private val locRepo: LocRepository,
    private val xpMods: XpModifiers,
    private val invisibleLvls: InvisibleLevels,
) : PluginScript() {
    private val logger = InlineLogger()

    override fun ScriptContext.startup() {
        bindHeatSources()
        bindCombinations()
    }

    private fun ScriptContext.bindHeatSources() {
        val lumbridgeRange = locTypes[cooking_locs.lumbridge_range].id
        var ranges = 0
        var fires = 0
        for (type in locTypes.values) {
            val heat = type.heatSource() ?: continue
            val lumbridge = type.id == lumbridgeRange
            for (recipe in CookingData.heat) {
                val raw = obj(recipe.raw)
                if (!recipe.fire && heat == HeatSource.Fire) {
                    onOpLocU(type, raw) { mes("This can only be cooked on a range.") }
                    continue
                }
                onOpLocU(type, raw) { cookAll(it.loc, it.type, heat, recipe, lumbridge) }
            }
            if (heat == HeatSource.Range) ranges++ else fires++
        }
        logger.info {
            "Cooking: ${CookingData.heat.size} heat recipes on $ranges range and $fires fire loc types."
        }
    }

    private fun ScriptContext.bindCombinations() {
        // Several products can share one ingredient pair (flour + water -> bread dough, pastry
        // dough or pizza base), and the Wiki lists some pairs in both orders. Group by unordered
        // pair so each pair registers once; multi-product pairs ask which to make.
        val pairs = LinkedHashMap<Set<String>, MutableList<CookingData.Combine>>()
        for (combo in CookingData.combine) {
            pairs.getOrPut(setOf(combo.first, combo.second)) { mutableListOf() }
                .takeIf { list -> list.none { it.product == combo.product } }
                ?.add(combo)
        }
        for ((_, combos) in pairs) {
            val first = combos[0]
            onOpHeldU(obj(first.first), obj(first.second)) { combineFrom(combos) }
        }
        logger.info { "Cooking: ${pairs.size} ingredient combinations." }
    }

    private fun UnpackedLocType.heatSource(): HeatSource? =
        when (name.lowercase()) {
            "range",
            "cooking range",
            "stove",
            "clay oven" -> HeatSource.Range
            "fire" -> HeatSource.Fire
            else -> null
        }

    private suspend fun ProtectedAccess.cookAll(
        loc: BoundLocInfo,
        locType: UnpackedLocType,
        heat: HeatSource,
        recipe: CookingData.Heat,
        lumbridgeRange: Boolean,
    ) {
        if (player.cookingLvl < recipe.level) {
            mes("You need a Cooking level of ${recipe.level} to cook this.")
            return
        }
        val raw = obj(recipe.raw)
        val cooked = obj(recipe.cooked)
        val burnt = recipe.burnt?.let(::obj)
        // Cook the whole inventory, one item every 4 ticks, until out of raw food, the fire burns
        // out, or the player does something else (which cancels this script).
        while (raw in inv) {
            if (locRepo.findExact(loc.coords, locType) == null) {
                return
            }
            faceSquare(loc.coords)
            anim(if (heat == HeatSource.Range) cooking_seqs.human_cooking else cooking_seqs.human_firecooking)
            delay(COOK_TICKS)
            if (raw !in inv) {
                return
            }
            val curve = curveFor(recipe, lumbridgeRange)
            val success = burnt == null || statRandom(stats.cooking, curve.low, curve.high, invisibleLvls)
            if (invDel(inv, raw, count = 1).failure) {
                return
            }
            val name = objTypes[cooked].name.lowercase()
            if (success) {
                invAdd(inv, cooked)
                statAdvance(stats.cooking, recipe.xp * xpMods.get(player, stats.cooking))
                spam("You successfully cook the $name.")
            } else {
                invAdd(inv, burnt!!)
                spam("You accidentally burn the $name.")
            }
        }
    }

    private fun ProtectedAccess.curveFor(
        recipe: CookingData.Heat,
        lumbridgeRange: Boolean,
    ): CookingData.Curve {
        val gloves = player.hands
        val gauntlets = recipe.gauntlets
        if (gauntlets != null && gloves != null && gloves.id == objTypes[cooking_objs.gauntlets_of_cooking].id) {
            return gauntlets
        }
        val lumbridge = recipe.lumbridge
        if (lumbridgeRange && lumbridge != null) {
            return lumbridge
        }
        return recipe.curve
    }

    private suspend fun ProtectedAccess.combineFrom(combos: List<CookingData.Combine>) {
        val combo =
            when (combos.size) {
                1 -> combos[0]
                2 -> choice2(label(combos[0]), combos[0], label(combos[1]), combos[1])
                else ->
                    choice3(
                        label(combos[0]), combos[0],
                        label(combos[1]), combos[1],
                        label(combos[2]), combos[2],
                    )
            }
        combine(combo)
    }

    private fun label(combo: CookingData.Combine): String = objTypes[obj(combo.product)].name

    private fun ProtectedAccess.combine(combo: CookingData.Combine) {
        if (player.cookingLvl < combo.level) {
            mes("You need a Cooking level of ${combo.level} to make that.")
            return
        }
        val first = obj(combo.first)
        val second = obj(combo.second)
        if (first !in inv || second !in inv) {
            return
        }
        val leftovers = listOfNotNull(combo.firstLeftover, combo.secondLeftover).map(::obj)
        // Two in, (1 + leftovers) out.
        if (inv.freeSpace() < leftovers.size - 1) {
            mes("You don't have enough inventory space to do that.")
            return
        }
        if (invDel(inv, first, count = 1).failure) {
            return
        }
        if (invDel(inv, second, count = 1).failure) {
            invAdd(inv, first)
            return
        }
        val product = obj(combo.product)
        invAdd(inv, product)
        leftovers.forEach { invAdd(inv, it) }
        if (combo.xp > 0) {
            statAdvance(stats.cooking, combo.xp * xpMods.get(player, stats.cooking))
        }
        mes("You make ${objTypes[product].name.lowercase()}.")
    }

    private fun obj(name: String): ObjType = cooking_objs.byName.getValue(name)

    private enum class HeatSource {
        Range,
        Fire,
    }

    private companion object {
        const val COOK_TICKS = 4
    }
}
