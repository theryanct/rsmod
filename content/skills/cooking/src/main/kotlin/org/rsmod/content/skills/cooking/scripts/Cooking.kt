// Data: content/skills/cooking/.../cooking.tsv, generated by tools/skills/cooking_to_tsv.py.
// Covers heat recipes (incl. karambwan; cake hands its tin back), two-item combinations (incl.
// stews, unfermented wine), 3+ ingredient recipes on a base item (cake) and wine fermentation.
// Not yet: Hosidius +10% (diary), poison karambwan, gnome cooking, brewing, fermenting in the bank.
class Cooking
@Inject
constructor(
    private val locTypes: LocTypeList,
    private val objTypes: ObjTypeList,
    private val locRepo: LocRepository,
    private val xpMods: XpModifiers,
    private val invisibleLvls: InvisibleLevels,
) : PluginScript() {
    private val logger = InlineLogger()

    override fun ScriptContext.startup() {
        bindHeatSources()
        bindCombinations()
        bindMulti()
        onPlayerTimer(CookingTimers.wine_ferment) { ferment() }
    }

    private fun ScriptContext.bindHeatSources() {
        val lumbridgeRange = locTypes[cooking_locs.lumbridge_range].id
        val hosidiusRanges =
            setOf(locTypes[cooking_locs.hosidius_range].id, locTypes[cooking_locs.hosidius_range_02].id)
        var ranges = 0
        var fires = 0
        var cookOps = 0
        for (type in locTypes.values) {
            val cookOp = type.op.indexOfFirst { it?.trim().equals("Cook", ignoreCase = true) }
            val heat = type.heatSource() ?: if (cookOp >= 0) HeatSource.Range else continue
            val bonus =
                when (type.id) {
                    lumbridgeRange -> RangeBonus.Lumbridge
                    in hosidiusRanges -> RangeBonus.Hosidius
                    else -> RangeBonus.None
                }
            // Use raw food on the heat source.
            for (recipe in CookingData.heat) {
                val raw = obj(recipe.raw)
                if (!recipe.fire && heat == HeatSource.Fire) {
                    onOpLocU(type, raw) { mes("This can only be cooked on a range.") }
                    continue
                }
                onOpLocU(type, raw) { cookAll(it.loc, it.type, heat, recipe, bonus) }
            }
            // Click "Cook" on the heat source (its slot differs per loc type).
            if (cookOp >= 0) {
                bindCookOp(type, cookOp + 1, heat, bonus)
                cookOps++
            }
            if (heat == HeatSource.Range) ranges++ else fires++
        }
        logger.info {
            "Cooking: ${CookingData.heat.size} heat recipes on $ranges range and $fires fire loc " +
                "types; Cook op bound on $cookOps."
        }
    }

    private fun ScriptContext.bindCookOp(
        type: UnpackedLocType,
        op: Int,
        heat: HeatSource,
        bonus: RangeBonus,
    ) {
        when (op) {
            1 -> if (!isLocOpBound(type, 1)) onOpLoc1(type) { cookFromInventory(it.loc, it.type, heat, bonus) }
            2 -> if (!isLocOpBound(type, 2)) onOpLoc2(type) { cookFromInventory(it.loc, it.type, heat, bonus) }
            3 -> if (!isLocOpBound(type, 3)) onOpLoc3(type) { cookFromInventory(it.loc, it.type, heat, bonus) }
            4 -> if (!isLocOpBound(type, 4)) onOpLoc4(type) { cookFromInventory(it.loc, it.type, heat, bonus) }
            5 -> if (!isLocOpBound(type, 5)) onOpLoc5(type) { cookFromInventory(it.loc, it.type, heat, bonus) }
        }
    }

    /** "Cook" clicked: offer every raw food in the inventory that this heat source can cook. */
    private suspend fun ProtectedAccess.cookFromInventory(
        loc: BoundLocInfo,
        locType: UnpackedLocType,
        heat: HeatSource,
        bonus: RangeBonus,
    ) {
        val cookable =
            CookingData.heat
                .filter { (it.fire || heat == HeatSource.Range) && obj(it.raw) in inv }
                .distinctBy { it.raw }
        if (cookable.isEmpty()) {
            mes("You have nothing to cook.")
            return
        }
        if (cookable.size == 1) {
            cookAll(loc, locType, heat, cookable[0], bonus)
            return
        }
        val shown = cookable.take(SKILLMULTI_SLOTS)
        val choice =
            skillMulti(
                verb = SkillMultiVerb.COOK,
                title = "What would you like to cook?",
                products =
                    shown.map {
                        val product = objTypes[obj(it.cooked)]
                        SkillMultiProduct(product, product.name, available = player.cookingLvl >= it.level)
                    },
                maxQuantity = shown.maxOf { invTotal(inv, obj(it.raw)) },
            )
        cookAll(loc, locType, heat, shown[choice.index], bonus, quantity = choice.quantity)
    }

    private fun ScriptContext.bindCombinations() {
        // Several products can share one ingredient pair (flour + water -> bread dough, pastry
        // dough or pizza base), and the Wiki lists some pairs in both orders. Group by unordered
        // pair so each pair registers once; multi-product pairs ask which to make.
        val pairs = LinkedHashMap<Set<String>, MutableList<CookingData.Combine>>()
        for (combo in CookingData.combine) {
            pairs.getOrPut(setOf(combo.first, combo.second)) { mutableListOf() }
                .takeIf { list -> list.none { it.product == combo.product } }
                ?.add(combo)
        }
        for ((_, combos) in pairs) {
            val first = combos[0]
            onOpHeldU(obj(first.first), obj(first.second)) { combineFrom(combos) }
        }
        logger.info { "Cooking: ${pairs.size} ingredient combinations." }
    }

    private fun UnpackedLocType.heatSource(): HeatSource? =
        when (name.lowercase()) {
            "range",
            "cooking range",
            "stove",
            "clay oven" -> HeatSource.Range
            "fire" -> HeatSource.Fire
            else -> null
        }

    private suspend fun ProtectedAccess.cookAll(
        loc: BoundLocInfo,
        locType: UnpackedLocType,
        heat: HeatSource,
        recipe: CookingData.Heat,
        bonus: RangeBonus,
        quantity: Int? = null,
    ) {
        if (player.cookingLvl < recipe.level) {
            mes("You need a Cooking level of ${recipe.level} to cook this.")
            return
        }
        val raw = obj(recipe.raw)
        val cooked = obj(recipe.cooked)
        val burnt = recipe.burnt?.let(::obj)
        // OSRS skillmulti "How many would you like to cook?" when there is more than one to cook.
        val held = invTotal(inv, raw)
        var remaining =
            if (quantity != null) {
                quantity
            } else if (held > 1) {
                val product = objTypes[cooked]
                skillMulti(
                        verb = SkillMultiVerb.COOK,
                        title = "How many would you like to cook?",
                        products = listOf(SkillMultiProduct(product, product.name, available = true)),
                        maxQuantity = held,
                    )
                    .quantity
            } else {
                1
            }
        // One item every 4 ticks until the chosen amount is done, the raw food runs out, the fire
        // burns out, or the player does something else (which cancels this script).
        while (remaining > 0 && raw in inv) {
            remaining--
            if (locRepo.findExact(loc.coords, locType) == null) {
                return
            }
            faceSquare(loc.coords)
            anim(if (heat == HeatSource.Range) cooking_seqs.human_cooking else cooking_seqs.human_firecooking)
            delay(COOK_TICKS)
            if (raw !in inv) {
                return
            }
            val curve = curveFor(recipe, if (heat == HeatSource.Range) bonus else RangeBonus.None)
            val success = burnt == null || statRandom(stats.cooking, curve.low, curve.high, invisibleLvls)
            if (invDel(inv, raw, count = 1).failure) {
                return
            }
            val name = objTypes[cooked].name.lowercase()
            if (success) {
                invAdd(inv, cooked)
                statAdvance(stats.cooking, recipe.xp * xpMods.get(player, stats.cooking))
                spam("You successfully cook the $name.")
            } else {
                invAdd(inv, burnt!!)
                spam("You accidentally burn the $name.")
            }
            recipe.returns?.let { invAdd(inv, obj(it)) }
        }
    }

    private fun ProtectedAccess.curveFor(
        recipe: CookingData.Heat,
        bonus: RangeBonus,
    ): CookingData.Curve {
        val gloves = player.hands
        val gauntlets = recipe.gauntlets
        if (gauntlets != null && gloves != null && gloves.id == objTypes[cooking_objs.gauntlets_of_cooking].id) {
            return gauntlets
        }
        val ranged =
            when (bonus) {
                RangeBonus.Lumbridge -> recipe.lumbridge
                RangeBonus.Hosidius -> recipe.hosidius
                RangeBonus.None -> null
            }
        return ranged ?: recipe.curve
    }

    private suspend fun ProtectedAccess.combineFrom(combos: List<CookingData.Combine>) {
        val first = obj(combos[0].first)
        val second = obj(combos[0].second)
        val sets = minOf(invTotal(inv, first), invTotal(inv, second))
        if (combos.size == 1 && sets <= 1) {
            combine(combos[0])
            return
        }
        // OSRS skillmulti: pick the product (flour + water -> bread dough / pastry dough / pizza
        // base) and how many to make.
        val choice =
            skillMulti(
                verb = SkillMultiVerb.MAKE,
                title = "What would you like to make?",
                products =
                    combos.map {
                        val product = objTypes[obj(it.product)]
                        SkillMultiProduct(product, product.name, available = player.cookingLvl >= it.level)
                    },
                maxQuantity = maxOf(1, sets),
            )
        val combo = combos[choice.index]
        repeat(choice.quantity) {
            if (!combine(combo)) {
                return
            }
            delay(COMBINE_TICKS)
        }
    }

    /** Makes one [combo]; returns `false` when it can't (stops a make-X run). */
    private fun ProtectedAccess.combine(combo: CookingData.Combine): Boolean {
        if (player.cookingLvl < combo.level) {
            mes("You need a Cooking level of ${combo.level} to make that.")
            return false
        }
        val first = obj(combo.first)
        val second = obj(combo.second)
        if (first !in inv || second !in inv) {
            return false
        }
        val leftovers = listOfNotNull(combo.firstLeftover, combo.secondLeftover).map(::obj)
        // Two in, (1 + leftovers) out.
        if (inv.freeSpace() < leftovers.size - 1) {
            mes("You don't have enough inventory space to do that.")
            return false
        }
        if (invDel(inv, first, count = 1).failure) {
            return false
        }
        if (invDel(inv, second, count = 1).failure) {
            invAdd(inv, first)
            return false
        }
        val product = obj(combo.product)
        invAdd(inv, product)
        leftovers.forEach { invAdd(inv, it) }
        if (combo.xp > 0) {
            statAdvance(stats.cooking, combo.xp * xpMods.get(player, stats.cooking))
        }
        spam("You make ${objTypes[product].name.lowercase()}.")
        if (CookingData.ferment.any { it.unfermented == combo.product }) {
            // OSRS: wine ferments 12 seconds after the last jug made; each new jug restarts it.
            player.timer(CookingTimers.wine_ferment, FERMENT_TICKS)
        }
        return true
    }

    /** Using any ingredient on the base (egg/flour/milk on a cake tin) makes the product. */
    private fun ScriptContext.bindMulti() {
        var pairs = 0
        for (recipe in CookingData.multi) {
            for (ingredient in recipe.ingredients) {
                onOpHeldU(obj(recipe.base), obj(ingredient)) { makeMulti(recipe) }
                pairs++
            }
        }
        logger.info { "Cooking: ${CookingData.multi.size} multi-ingredient recipes ($pairs pairs)." }
    }

    private suspend fun ProtectedAccess.makeMulti(recipe: CookingData.Multi) {
        val inputs = (listOf(recipe.base) + recipe.ingredients).map(::obj)
        val missing = inputs.filter { it !in inv }
        if (missing.isNotEmpty()) {
            mes("You also need ${missing.joinToString(" and ") { objTypes[it].name.lowercase() }}.")
            return
        }
        val sets = inputs.minOf { invTotal(inv, it) }
        val quantity =
            if (sets > 1) {
                val product = objTypes[obj(recipe.product)]
                skillMulti(
                        verb = SkillMultiVerb.MAKE,
                        title = "How many would you like to make?",
                        products = listOf(SkillMultiProduct(product, product.name, available = true)),
                        maxQuantity = sets,
                    )
                    .quantity
            } else {
                1
            }
        repeat(quantity) {
            if (!multi(recipe, inputs)) {
                return
            }
            delay(COMBINE_TICKS)
        }
    }

    private fun ProtectedAccess.multi(recipe: CookingData.Multi, inputs: List<ObjType>): Boolean {
        if (player.cookingLvl < recipe.level) {
            mes("You need a Cooking level of ${recipe.level} to make that.")
            return false
        }
        if (inputs.any { it !in inv }) {
            return false
        }
        // N in, (1 + leftovers) out: never needs more space than it frees.
        for (input in inputs) {
            invDel(inv, input, count = 1)
        }
        val product = obj(recipe.product)
        invAdd(inv, product)
        recipe.leftovers.forEach { invAdd(inv, obj(it)) }
        if (recipe.xp > 0) {
            statAdvance(stats.cooking, recipe.xp * xpMods.get(player, stats.cooking))
        }
        spam("You make ${objTypes[product].name.lowercase()}.")
        return true
    }

    /**
     * Wine fermentation: every unfermented jug in the inventory turns into wine (200 xp) or bad
     * wine, rolled on the Wiki "Jug of wine" curve (about 60% at 35, certain from 68).
     */
    private fun ProtectedAccess.ferment() {
        player.clearTimer(CookingTimers.wine_ferment)
        for (recipe in CookingData.ferment) {
            val unfermented = obj(recipe.unfermented)
            val count = invTotal(inv, unfermented)
            if (count <= 0) {
                continue
            }
            var good = 0
            repeat(count) {
                if (statRandom(stats.cooking, recipe.curve.low, recipe.curve.high, invisibleLvls)) good++
            }
            invDel(inv, unfermented, count)
            if (good > 0) {
                invAdd(inv, obj(recipe.fermented), good)
                statAdvance(stats.cooking, recipe.xp * good * xpMods.get(player, stats.cooking))
            }
            if (count - good > 0) {
                invAdd(inv, obj(recipe.failed), count - good)
            }
            mes(if (good == count) "The wine has fermented." else "Some of the wine has fermented badly.")
        }
    }

    private fun obj(name: String): ObjType = cooking_objs.byName.getValue(name)

    private enum class RangeBonus {
        None,
        Lumbridge,
        Hosidius,
    }

    private enum class HeatSource {
        Range,
        Fire,
    }

    private companion object {
        const val COOK_TICKS = 4
        const val COMBINE_TICKS = 2
        /** 12 seconds. */
        const val FERMENT_TICKS = 20
        /** Rev 243 skillmulti names 18 item slots (`a`-`r`). */
        const val SKILLMULTI_SLOTS = 18
    }
}
